// 触发器脚本桥接模块源码（P3 第二十三批自 script-supervisor.ts 拆出，文件行数上限）：
// 引擎 spawn 前把源码写进工作区 state/（幂等重写），经 --require（node）/ PYTHONPATH
// （python）注入脚本进程。内容为纯常量、零依赖——与监督逻辑无耦合，拆分边界干净。
// ack/暂停语义的正身说明见 docs/trigger-system.md「事件上报协议」与
// specs/trigger-browser-hosting.md §3.4（login_failed 暂停通道）。

/**
 * 引擎生成的桥接模块源码（纯 Node 内置、零 npm 依赖）：`--require` 预加载后向脚本注入
 * `globalThis.robindone = { emit(event) → Promise(ack), onShutdown(fn) }`。ack 语义见
 * 「事件上报协议」：emit 在引擎接受事件后 resolve（契约违例 reject），一次性脚本
 * `await emit()` 后退出即无投递竞态。
 */
export const BRIDGE_SOURCE = `/* RobinDone trigger bridge (generated by the engine; do not edit). */
"use strict";
(function () {
  if (typeof process.send !== "function") return;
  var seq = 0;
  var pending = new Map();
  var shutdownHandlers = [];
  process.on("message", function (msg) {
    if (!msg || typeof msg !== "object") return;
    if (msg.type === "robindone-ack") {
      var waiter = pending.get(msg.id);
      if (!waiter) return;
      pending.delete(msg.id);
      if (msg.ok) waiter.resolve();
      else waiter.reject(new Error(msg.error || "event rejected by the engine"));
      return;
    }
    if (msg.type === "robindone-shutdown") {
      var handlers = shutdownHandlers.splice(0);
      for (var i = 0; i < handlers.length; i++) {
        try { handlers[i](); } catch (error) { /* 收尾钩子互不影响 */ }
      }
    }
  });
  Object.defineProperty(globalThis, "robindone", {
    value: {
      emit: function (event) {
        return new Promise(function (resolve, reject) {
          seq += 1;
          var id = seq;
          pending.set(id, { resolve: resolve, reject: reject });
          process.send({ type: "robindone-event", id: id, event: event });
        });
      },
      onShutdown: function (handler) {
        if (typeof handler === "function") shutdownHandlers.push(handler);
      },
      // 登录闭环（2026-11-25）：登录检测失败上报（HTTP pause 端点；node 也走 HTTP——
      // 与 python 桥接同一条引擎收口，无需为单语义扩 IPC 协议）。
      loginFailed: function (reason) {
        var url = process.env.ROBINDONE_PAUSE_URL;
        if (!url) {
          return Promise.reject(
            new Error("ROBINDONE_PAUSE_URL is not set; this script must be started by the RobinDone engine"),
          );
        }
        return fetch(url, {
          method: "POST",
          headers: { "content-type": "application/json" },
          body: JSON.stringify({ reason: reason || "" }),
        }).then(function (response) { return response.json(); });
      },
    },
    writable: false,
    enumerable: false,
    configurable: false,
  });
})();
`;

/**
 * python 桥接模块源码（2026-11-22 HTTP emit 协议，对齐 node 的 `robindone.emit` 注入模式）：
 * 引擎 spawn python 前写进 `state/robindone.py`，经 `PYTHONPATH` 注入——脚本 `import robindone`
 * 即得 `emit(summary, data=None)`。stdlib-only（urllib）；HTTP/URL/JSON 全部封装在库内，
 * agent 不构建请求；引擎契约校验同步完成后才响应，违例 raise（同 node IPC 的 reject 语义）。
 * stdout 专职日志（事件协议已退役），print 不会污染事件通道。
 */
export const PYTHON_BRIDGE_SOURCE = `"""RobinDone trigger bridge (generated by the engine; do not edit)."""
import json
import os
import urllib.error
import urllib.request

def _post(url, payload):
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url, data=body, headers={"Content-Type": "application/json"}, method="POST"
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        try:
            return json.loads(error.read().decode("utf-8"))
        except Exception:
            raise RuntimeError("robindone request failed: HTTP %d" % error.code) from error
    except OSError as error:
        raise RuntimeError("robindone request failed: %s" % error) from error

def emit(summary, data=None):
    """Report one event to the engine and wait for its acknowledgement.

    Raises RuntimeError when the engine rejects the event (contract violation)
    or the endpoint is unreachable; returns the engine's response dict on
    success. Events must satisfy the trigger's registry \`contract\` assertions
    against \`data\`.
    """
    url = os.environ.get("ROBINDONE_EMIT_URL")
    if not url:
        raise RuntimeError(
            "ROBINDONE_EMIT_URL is not set; this script must be started by the RobinDone engine"
        )
    result = _post(url, {"summary": summary, "data": data})
    if not result.get("ok"):
        raise RuntimeError(result.get("error") or "event rejected by the engine")
    return result

def login_failed(reason=""):
    """Report that this script's login check failed (2026-11-25 login closed loop).

    The engine pauses the trigger (error-paused), wakes the subscriber agent
    with the diagnostics, and stops this script. Call it when your own login
    detection (e.g. a 401 or a redirect to the login page) concludes the saved
    login state no longer works, then exit. The agent repairs the login via
    ManageTriggers open_login and re-enables the trigger.
    """
    url = os.environ.get("ROBINDONE_PAUSE_URL")
    if not url:
        raise RuntimeError(
            "ROBINDONE_PAUSE_URL is not set; this script must be started by the RobinDone engine"
        )
    return _post(url, {"reason": reason})
`;
